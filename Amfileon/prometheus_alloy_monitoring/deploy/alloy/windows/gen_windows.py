#!/usr/bin/env python3
"""Writes install-alloy-<host>.ps1 — one self-contained script for a Windows host (no ssh there):
copy it over RDP and run it as Administrator. It embeds config.alloy and the Amfileon CA.

    python3 gen_windows.py prod2 10.10.10.12

The script downloads the Alloy installer (checksum-verified), installs the "Alloy" service, asks
for the two passwords from deploy/secrets/alloy.env (hidden input, stored in files only SYSTEM and
Administrators can read), lets the service listen on the host's LAN IP:12345 and opens that port in
the Windows firewall for db1 only (host-alive check). Safe to run again (keeps stored passwords).
"""
import pathlib
import sys

here = pathlib.Path(__file__).parent
host, ip = sys.argv[1], sys.argv[2]
VERSION = "v1.21.2"
ZIP_SHA256 = "383b01ca3556c96a409b9488b1a9ef891b726db1d931c73f657613d21215548e"   # GitHub release digest
DB1 = "10.10.10.20"

config = (here / "config.alloy").read_text().replace("__AMF_HOST__", host)
ca = (here.parent.parent / "ca" / "amfileon-ca.pem").read_text().strip()
assert "'@" not in config and "'@" not in ca

ps1 = f"""#Requires -RunAsAdministrator
# install-alloy-{host}.ps1 — GENERATED by prometheus_alloy_monitoring/deploy/alloy/windows/gen_windows.py
# Run on {host} ({ip}) as Administrator:  powershell -ExecutionPolicy Bypass -File .\\install-alloy-{host}.ps1
# Installs Grafana Alloy {VERSION} as Windows service "Alloy" → pushes this host's metrics to Prometheus
# on db1 and db2 (TLS + login). Nothing else on this server is changed.
# Uninstall: "C:\\Program Files\\GrafanaLabs\\Alloy\\uninstall.exe" /S ; Remove-NetFirewallRule -DisplayName 'Amfileon Alloy (db1 host-alive)'
$ErrorActionPreference = 'Stop'
$HostIP     = '{ip}'
$Db1        = '{DB1}'
$Dir        = 'C:\\ProgramData\\Amfileon\\alloy'
$InstallDir = 'C:\\Program Files\\GrafanaLabs\\Alloy'
$Url        = 'https://github.com/grafana/alloy/releases/download/{VERSION}/alloy-installer-windows-amd64.exe.zip'
$Sha256     = '{ZIP_SHA256}'
$Utf8NoBom  = New-Object System.Text.UTF8Encoding($false)

Write-Host '==> folder for CA and passwords (SYSTEM + Administrators only)'
New-Item -ItemType Directory -Force -Path $Dir | Out-Null
# SIDs, not names: works on any Windows language (German: "Administratoren")
icacls $Dir /inheritance:r /grant:r '*S-1-5-18:(OI)(CI)F' '*S-1-5-32-544:(OI)(CI)F' | Out-Null
if ($LASTEXITCODE -ne 0) {{ throw 'could not restrict the folder permissions - nothing installed' }}

[IO.File]::WriteAllText("$Dir\\amfileon-ca.pem", @'
{ca}
'@, $Utf8NoBom)

function Save-Secret([string]$Name, [string]$File) {{
  if (Test-Path "$Dir\\$File") {{ Write-Host "    $Name already stored - kept"; return }}
  $s = Read-Host -AsSecureString "$Name (from deploy/secrets/alloy.env, not shown)"
  $b = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($s)
  try {{ $p = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($b) }} finally {{ [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($b) }}
  if (-not $p) {{ throw "$Name is empty - nothing installed" }}
  [IO.File]::WriteAllText("$Dir\\$File", $p, $Utf8NoBom)
  Remove-Variable p
}}
Write-Host '==> passwords'
Save-Secret 'ALLOY_PASSWORD' 'alloy_password'
Save-Secret 'ALLOY_HTTP_PASSWORD' 'alloy_http_password'

Write-Host '==> Alloy installer {VERSION}'
$ProgressPreference = 'SilentlyContinue'   # the progress bar makes Invoke-WebRequest ~10x slower
$zip = Join-Path $PSScriptRoot 'alloy-installer-windows-amd64.exe.zip'
if (-not (Test-Path $zip)) {{
  [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
  $zip = "$env:TEMP\\alloy-installer-windows-amd64.exe.zip"
  try {{ Invoke-WebRequest -Uri $Url -OutFile $zip -UseBasicParsing }}
  catch {{ throw "download failed (no internet?) - put alloy-installer-windows-amd64.exe.zip next to this script: $Url" }}
}}
if ((Get-FileHash $zip -Algorithm SHA256).Hash -ne $Sha256.ToUpper()) {{ throw 'installer checksum mismatch - nothing installed' }}
$tmp = "$env:TEMP\\alloy-installer"
Expand-Archive -Path $zip -DestinationPath $tmp -Force
Start-Process -Wait -FilePath "$tmp\\alloy-installer-windows-amd64.exe" -ArgumentList '/S', '/DISABLEREPORTING=yes'

Write-Host '==> config and service arguments'
[IO.File]::WriteAllText("$InstallDir\\config.alloy", @'
{config}'@, $Utf8NoBom)
Set-ItemProperty -Path 'HKLM:\\SOFTWARE\\GrafanaLabs\\Alloy' -Name 'Arguments' -Type MultiString -Value @(
  'run', "$InstallDir\\config.alloy",
  '--storage.path=C:\\ProgramData\\GrafanaLabs\\Alloy\\data',
  "--server.http.listen-addr=$($HostIP):12345",
  '--disable-reporting')

Write-Host '==> firewall: port 12345 from db1 only'
if (-not (Get-NetFirewallRule -DisplayName 'Amfileon Alloy (db1 host-alive)' -ErrorAction SilentlyContinue)) {{
  New-NetFirewallRule -DisplayName 'Amfileon Alloy (db1 host-alive)' -Direction Inbound -Protocol TCP `
    -LocalPort 12345 -RemoteAddress $Db1 -Action Allow | Out-Null
}}

Write-Host '==> (re)starting the Alloy service'
Set-Service -Name Alloy -StartupType Automatic
Restart-Service -Name Alloy
Start-Sleep -Seconds 15
Get-Service -Name Alloy | Format-Table -AutoSize Name, Status, StartType
try {{ (Invoke-WebRequest -Uri "http://$($HostIP):12345/-/ready" -UseBasicParsing -TimeoutSec 10).Content }}
catch {{ Write-Warning "Alloy not ready yet - see Event Viewer > Windows Logs > Application (source Alloy)" }}
Write-Host '==> done. Tell Claude to verify.'
"""
out = here / f"install-alloy-{host}.ps1"
out.write_text(ps1)
print(f"wrote {out.name} ({len(ps1.splitlines())} lines)")

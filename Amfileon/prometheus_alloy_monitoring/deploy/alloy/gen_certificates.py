#!/usr/bin/env python3
"""Writes alloy/hosts/<host>.certificates.alloy from alloy/certificate-targets.txt.

A host's Alloy probes each of its names on :443 with full TLS verification against the Amfileon CA
(Alloy's built-in blackbox exporter) and pushes probe_success / probe_ssl_earliest_cert_expiry,
labelled certificate="<name>", to both Prometheus instances. Checks run on cpu2 — an Alloy that joins no service networks. On a host whose Alloy is in a
service's Docker network, Docker's DNS answers that network's container names first (ClickHouse
containers are named db1.production.ch.amf, GitLab has hostname gitlab.amf, …), so the check would
hit the container instead of nginx-proxy (seen 2026-10-28/29 on db1: 5 false CertificateCheckFailed).
A line is "<name>" (checked by cpu2) or "<name> <host>".
"""
import pathlib

here = pathlib.Path(__file__).parent
by_host = {}
for l in (here / "certificate-targets.txt").read_text().splitlines():
    if l.strip() and not l.lstrip().startswith("#"):
        f = l.split()
        by_host.setdefault(f[1] if len(f) > 1 and not f[1].startswith("#") else "cpu2", []).append(f[0])

for old in (here / "hosts").glob("*.certificates.*"):
    old.unlink()
for host, names in sorted(by_host.items()):
    targets = "\n".join(
        f'    {{ name = "{n.replace(".", "_")}", address = "{n}:443", module = "amf_tls" }},' for n in names)
    (here / "hosts" / f"{host}.certificates.alloy").write_text(f'''// GENERATED by alloy/gen_certificates.py from certificate-targets.txt — edit that file instead.
// Certificate expiry: {host}'s Alloy checks {len(names)} HTTPS names every minute.

prometheus.exporter.blackbox "certificates" {{
  config  = "{{ modules: {{ amf_tls: {{ prober: tcp, timeout: 10s, tcp: {{ tls: true, tls_config: {{ ca_file: /etc/alloy-ca/amfileon-ca.pem }} }} }} }} }}"
  targets = [
{targets}
  ]
}}

// readable labels: certificate="<name>", job="certificates"
discovery.relabel "certificates" {{
  targets = prometheus.exporter.blackbox.certificates.targets
  rule {{
    source_labels = ["__param_target"]
    regex         = "(.*):443"
    target_label  = "certificate"
  }}
  rule {{
    target_label = "job"
    replacement  = "certificates"
  }}
}}

prometheus.scrape "certificates" {{
  targets         = discovery.relabel.certificates.output
  scrape_interval = "1m"   // must stay below Prometheus' 5-minute staleness window, or values flicker and alerts reset
  scrape_timeout  = "30s"
  // the prober is served by Alloy's own HTTP server, which requires the login (http.alloy)
  basic_auth {{
    username = "admin"
    password = sys.env("ALLOY_HTTP_PASSWORD")
  }}
  forward_to = [prometheus.remote_write.both.receiver]
}}
''')
    print(f"wrote hosts/{host}.certificates.alloy with {len(names)} targets")

#!/usr/bin/env bash
# Run ONCE on your own machine (needs htpasswd + openssl; macOS has both).
#
# Writes ready-to-copy .env files into deploy/secrets/ (git-ignored, mode 700):
#   prometheus.env      → /srv/docker/prometheus/.env on db2   (bcrypt hashes only)
#   prometheus-db1.env  → /srv/docker/prometheus/.env on db1   (hashes + grafana password)
#   alloy.env       → /srv/docker/alloy/.env on every host        (ALLOY_PASSWORD)
#   grafana.env     → for the Grafana datasources on db1          (GRAFANA_PROMETHEUS_PASSWORD)
#   grafana-admin.env → admin login of https://grafana.amf        (GRAFANA_ADMIN_PASSWORD)
#
# Nothing is printed. Afterwards store the two passwords (alloy.env, grafana.env) in Infisical /
# your password manager. Re-running keeps existing passwords.
set -euo pipefail
cd "$(dirname "$0")"
umask 077
mkdir -p secrets && chmod 700 secrets

newpw() { openssl rand -base64 24 | tr -d '/+=\n'; }
[ -f secrets/alloy.env ]   || printf 'ALLOY_PASSWORD=%s\n' "$(newpw)" > secrets/alloy.env
[ -f secrets/grafana.env ] || printf 'GRAFANA_PROMETHEUS_PASSWORD=%s\n' "$(newpw)" > secrets/grafana.env
[ -f secrets/grafana-admin.env ] || printf 'GRAFANA_ADMIN_PASSWORD=%s\n' "$(newpw)" > secrets/grafana-admin.env
grep -q '^ALLOY_HTTP_PASSWORD=' secrets/alloy.env || printf 'ALLOY_HTTP_PASSWORD=%s\n' "$(newpw)" >> secrets/alloy.env

# Read the passwords back without echoing them.
alloy_pw=$(sed -n 's/^ALLOY_PASSWORD=//p' secrets/alloy.env)
grafana_pw=$(sed -n 's/^GRAFANA_PROMETHEUS_PASSWORD=//p' secrets/grafana.env)

# Empty username on purpose: `htpasswd -nBC 12 monitor | tr -d ':\n'` (from the notes) leaves
# "monitor" glued to the front of the hash, and no password would ever match it.
hash() { htpasswd -nbBC 12 "" "$1" | tr -d ':\n'; }

# Single quotes: bcrypt hashes contain '$', which docker compose would otherwise try to expand.
cat > secrets/prometheus.env <<EOF
# /srv/docker/prometheus/.env (db1 + db2) — generated by deploy/gen-secrets.sh, do not commit
PROMETHEUS_ALLOYUSER_HASH='$(hash "$alloy_pw")'
PROMETHEUS_GRAFANA_HASH='$(hash "$grafana_pw")'
EOF

# db1's Prometheus also needs the plain grafana password (it scrapes itself and db2 with it).
# ALERT_WEBHOOK_URL / HEALTHCHECKS_PING_URL are added by hand on db1 — see db1/INSTALL.md.
{ cat secrets/prometheus.env; cat secrets/grafana.env; } \
  | sed '1s|.*|# /srv/docker/prometheus/.env (db1) — generated by deploy/gen-secrets.sh, do not commit|' \
  > secrets/prometheus-db1.env

unset alloy_pw grafana_pw
echo "Wrote deploy/secrets/{prometheus.env,prometheus-db1.env,alloy.env,grafana.env,grafana-admin.env}."
echo "Store the passwords from alloy.env, grafana.env and grafana-admin.env in Infisical / your password manager."

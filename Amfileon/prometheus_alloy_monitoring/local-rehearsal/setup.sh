#!/usr/bin/env bash
# One-time setup for the rehearsal: passwords, a private CA + server certificates, and Prometheus'
# web.yml. Mirrors the manual steps in the team's notes ("Create 2x Basic Auth passwords",
# "MAKE SURE CA is installed").
set -euo pipefail
cd "$(dirname "$0")"

# ── passwords (.env is read by docker compose and by run-acceptance-tests.sh) ──
if [ ! -f .env ]; then
  cat > .env <<EOF
ALLOY_PASSWORD=$(openssl rand -hex 12)
GRAFANA_DS_PASSWORD=$(openssl rand -hex 12)
EOF
fi
set -a; . ./.env; set +a

# ── private CA + one server certificate per Prometheus ──
mkdir -p certs
if [ ! -f certs/ca.pem ]; then
  openssl req -x509 -newkey rsa:2048 -nodes -days 365 -subj "/CN=Amfileon rehearsal CA" \
    -keyout certs/ca.key -out certs/ca.pem 2>/dev/null
fi
for name in db1.prometheus.amf db2.prometheus.amf; do
  [ -f "certs/$name.pem" ] && continue
  openssl req -newkey rsa:2048 -nodes -subj "/CN=$name" -keyout "certs/$name.key" -out "certs/$name.csr" 2>/dev/null
  openssl x509 -req -in "certs/$name.csr" -CA certs/ca.pem -CAkey certs/ca.key -CAcreateserial -days 365 \
    -extfile <(printf "subjectAltName=DNS:%s" "$name") -out "certs/$name.pem" 2>/dev/null
  rm "certs/$name.csr"
done
chmod 644 certs/*.key   # readable by the nginx container user in this rehearsal only

# ── Prometheus basic-auth users ──
# NOTE: the notes use `htpasswd -nBC 12 monitor | tr -d ':\n'`, which leaves the username glued
# to the front of the hash ("monitor$2y$12$..."), so no password would ever match.
# An empty username yields just the hash.
hash() { htpasswd -nbBC 12 "" "$1" | tr -d ':\n'; }
cat > prometheus/web.yml <<EOF
# generated by setup.sh
basic_auth_users:
  alloyuser: $(hash "$ALLOY_PASSWORD")
  grafana: $(hash "$GRAFANA_DS_PASSWORD")
EOF

echo "setup done: .env, certs/, prometheus/web.yml"
